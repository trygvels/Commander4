def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="nextgen/params/q1")
    ap.add_argument("--nside", type=int, default=64)
    ap.add_argument("--fwhm", type=float, default=120.0)
    ap.add_argument("--niter", type=int, default=400)
    ap.add_argument("--numstep", type=int, default=10)
    ap.add_argument("--no-hfi", action="store_true")
    ap.add_argument("--pol", default="IQU")
    ap.add_argument("--modes", nargs="*", default=["ridge", "conditional", "marginal", "resolve_chisq"])
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    for mode in a.modes:
        tag = f"{mode}{'_nohfi' if a.no_hfi else ''}"
        p = os.path.join(a.out, f"param_q1_n{a.nside}_{tag}.yml")
        with open(p, "w") as fh:
            fh.write(make(mode, a.nside, a.fwhm, a.niter, a.numstep, a.out, not a.no_hfi, a.pol))
        print(p)


if __name__ == "__main__":
    main()
