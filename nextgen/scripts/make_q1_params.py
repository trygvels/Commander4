def band(name, sig_path, sig_cols, rms_path, rms_cols, fwhm, freq, pol, units, nside):
    return f"""    {name}:
      enabled: true
      get_from: "file"
      eval_nside: {nside}
      signal_map:
        path: "{sig_path}"
        dataset_names: {sig_cols}
      rms_map:
        type: "rms"
        path: "{rms_path}"
        dataset_names: {rms_cols}
      fwhm: {fwhm}
      freq: {freq}
      polarization: "{pol}"
      units: "{units}"
"""


