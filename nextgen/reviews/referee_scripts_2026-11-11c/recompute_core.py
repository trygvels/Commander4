"""Referee recomputation of the numbers of Sect. 6 of Paper A1 (draft 4) from the E044 result files. Reads only."""
import numpy as np
np.set_printoptions(precision=5, suppress=True, linewidth=160)
E = "nextgen/experiments/E044/"
L = lambda t: np.load(E + t + ".npz", allow_pickle=True)
z, w, f = L("lcdm_all"), L("white"), L("flat")
b0, s0, nper = z["beta"], z["sd_sand"], z["nper"].astype(float)
print("== central fit")
print("beta", b0, "sd_sand", s0, "sd_naive", z["sd_naive"])
print("nper", nper, "kept", z["keep"].sum(), "of", z["keep"].size, "converged", z["converged"], z["flat_converged"], z["zm_converged"])
J, T = z["J"], z["T"]
Jc = J - T
# independent sandwich: Jc^-1 J Jc^-1
cov = np.linalg.inv(Jc) @ J @ np.linalg.inv(Jc)
print("my debiased sandwich sd", np.sqrt(np.diag(cov)), "stored cov_sand diag sqrt", np.sqrt(np.diag(z["cov_sand"])))
print("T/Jc diag", np.diag(T) / np.diag(Jc), " snr2", np.diag(Jc) / np.diag(T), " T/J(plug-in)", np.diag(T) / np.diag(J))
print("n sd^2", nper * s0 ** 2)
print("corr of estimates\n", cov / np.sqrt(np.outer(np.diag(cov), np.diag(cov))))
chi2, dof = float(z["chi2"]), int(z["dof"])
n, nb = int(z["keep"].sum()), z["resid"].shape[0]
print("chi2", chi2, "dof", dof, "my dof", nb * n - 2 * n - 4, "ratio", chi2 / dof, "nsig", (chi2 - dof) / np.sqrt(2 * dof), "noise %", 100 * (1 - np.sqrt(chi2 / dof)))
pen = chi2 - float(np.sum(z["chi2_region"] * nper * nb))
print("chi2 region", z["chi2_region"], "penalty", pen, "expected per el and band", (dof - pen) / (n * nb))
cexp = (dof - pen) / (n * nb)
cse = np.sqrt(2.0 * (nb - 2) * nper) / (nper * nb)
print("se per region", cse, "z", (z["chi2_region"] - cexp) / cse)
from math import erfc, sqrt
for x in (2.5, (dof - chi2) / np.sqrt(2 * dof), 3.35):
    print("  one-sided p for", round(float(x), 3), "=", 0.5 * erfc(x / sqrt(2)), " 1 in", 1 / (0.5 * erfc(x / sqrt(2))))
print("== flat priors, LCDM")
d23, d30, dd = z["flat23"] - b0, z["flat30"] - b0, z["flat30"] - z["flat23"]
print("flat23", z["flat23"], "flat30", z["flat30"])
print("d23", d23, "in sd", d23 / s0)
print("d30", d30, "in sd", d30 / s0)
print("30-23", dd, "in sd", dd / s0)
print("pred_marg", z["pred_marg"], "my", np.linalg.solve(z["Hmarg"], nper * np.log(30 / 23)))
print("pred_jc", z["pred_jc"], "my", np.linalg.solve(Jc, nper * np.log(30 / 23)))
print("meas/predH", dd / z["pred_marg"], "predH over %", 100 * (z["pred_marg"] / dd - 1))
print("meas/predJ", dd / z["pred_jc"], "predJ over %", 100 * (z["pred_jc"] / dd - 1))
print("single-region n sd^2 ln(30/23)", nper * s0 ** 2 * np.log(30 / 23), " with 1/Jc_rr", nper / np.diag(Jc) * np.log(30 / 23))
hn = z["pred_marg"] / np.log(30 / 23)
print("pivot (generator)", 23.0 / np.exp(d23 / hn))
print("Hmarg diag", np.diag(z["Hmarg"]), "J diag", np.diag(J), "Jc diag", np.diag(Jc), "eig Hmarg", np.linalg.eigvalsh(z["Hmarg"]))
print("== zero mean")
print("zm", z["zm"], "zm-prof", z["zm"] - b0, "in sd", (z["zm"] - b0) / s0, "tau", z["zm_tau"])
print("== block")
print("CR3", z["blk_CR3"], "own", z["blk_CR3_own"], "ratio own", z["blk_CR3_own"] / s0, "neff", z["blk_neff"], "levmax", z["blk_lev_max"])
G, D = z["blk_G"], z["blk_D"]
Jci = np.linalg.inv(Jc)
for r in range(4):
    Dr = np.clip(D[:, r], 0, None)
    h = Dr / Dr.sum()
    v = Jci[r, r] ** 2 * np.sum(G[:, r] ** 2 / (1 - h) ** 2)
    print("  region", r, "my CR3_own", np.sqrt(v), "neff", Dr.sum() ** 2 / np.sum(Dr ** 2), "patches with D>0", int((D[:, r] > 0).sum()), "sum G", G[:, r].sum(), " sumD/Jc", D[:, r].sum() / Jc[r, r])
print("== white")
print("beta", w["beta"], "sd", w["sd_sand"], "move", w["beta"] - b0, "sd ratio to lcdm", w["sd_sand"] / s0)
sdt = np.sqrt(np.diag(w["mm_cov_true"]))
print("mm bias", w["mm_bias"], "bias/sd", w["mm_bias"] / w["sd_sand"], "sd true", sdt, "ratio", sdt / w["sd_sand"], "true/lcdm", sdt / s0)
pair = np.sqrt(sdt ** 2 - s0 ** 2)
print("pair sd", pair, "move-bias in pair", (w["beta"] - b0 - w["mm_bias"]) / pair, "corr HL-Int", w["mm_cov_true"][0, 2] / (sdt[0] * sdt[2]))
Jw, Tw = w["J"], w["T"]; Jcw = Jw - Tw
print("white: Jc^-1 (J + dK) Jc^-1 check:", np.sqrt(np.diag(np.linalg.inv(Jcw) @ (Jw + w["mm_dK"]) @ np.linalg.inv(Jcw))), " -Jc^-1 eg:", -np.linalg.solve(Jcw, w["mm_eg"]))
print("white dK diag over J diag", np.diag(w["mm_dK"]) / np.diag(Jw))
print("white chi2", float(w["chi2"]), int(w["dof"]), float(w["chi2"]) / int(w["dof"]), "region", w["chi2_region"])
print("white flat23", w["flat23"], "flat30", w["flat30"], "30-23", w["flat30"] - w["flat23"])
print("== flat CMB")
print("beta", f["beta"], "sd", f["sd_sand"], "ratio", f["sd_sand"] / s0, "move", f["beta"] - b0, "nest", (f["beta"] - b0) / np.sqrt(f["sd_sand"] ** 2 - s0 ** 2))
c2, df = float(f["chi2"]), int(f["dof"])
print("chi2", c2, df, "my dof", 5 * n - 3 * n - 4, c2 / df, "nsig", (c2 - df) / np.sqrt(2 * df), "noise%", 100 * (1 - np.sqrt(c2 / df)), "region", f["chi2_region"])
print("  one-sided p", 0.5 * erfc(abs(c2 - df) / np.sqrt(2 * df) / sqrt(2)), "1 in", 1 / (0.5 * erfc(abs(c2 - df) / np.sqrt(2 * df) / sqrt(2))))
print("cmb direction", (chi2 - c2), "/", n, "=", (chi2 - c2) / n, "+-", np.sqrt(2 / n), "; rest", c2 / df, "+-", np.sqrt(2 / df), "diff sig", ((chi2 - c2) / n - c2 / df) / np.sqrt(2 / n + 2 / df))
print("flat23", f["flat23"], "flat30", f["flat30"], "conv", f["flat_converged"], "f23-prof", f["flat23"] - f["beta"], "f30-prof", f["flat30"] - f["beta"])
print("Hmarg\n", f["Hmarg"], "\neig", np.linalg.eigvalsh(f["Hmarg"]), "J diag", np.diag(f["J"]), "Jc diag", np.diag(f["J"] - f["T"]), "T/Jc", np.diag(f["T"]) / np.diag(f["J"] - f["T"]))
print("n sd^2 flat", f["nper"] * f["sd_sand"] ** 2)
hn = f["pred_marg"] / np.log(30 / 23)
print("flat 'pivot' as the generator computes it", 23.0 / np.exp((f["flat23"] - f["beta"]) / hn), "pred_marg", f["pred_marg"])
hn = w["pred_marg"] / np.log(30 / 23)
print("white pivot", 23.0 / np.exp((w["flat23"] - w["beta"]) / hn))
